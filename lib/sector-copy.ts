export function sectorCopy(locale: LocaleId, sector: Pick<Sector, "id" | "label" | "blurb">) {
  if (locale === "tr") return { label: sector.label, blurb: sector.blurb }
  const translated = locale === "en" ? undefined : native[sector.id]?.[locale]
  if (translated) return { label: translated[0], blurb: translated[1] }
  const english = en[sector.id]
  if (english) return { label: english[0], blurb: english[1] }
  return { label: sector.label, blurb: sector.blurb }
}
